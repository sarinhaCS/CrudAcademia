private void carregarCombos() {
        try {
            AlunoDAO alunoDAO = new AlunoDAO();
            cbAluno.removeAllItems();
            for (Aluno a : alunoDAO.listar()) {
                cbAluno.addItem(a);
            }

            PlanoDAO planoDAO = new PlanoDAO();
            cbPlano.removeAllItems();
            for (Plano p : planoDAO.listar()) {
                cbPlano.addItem(p);
            }

            ModalidadeDAO modDAO = new ModalidadeDAO();
            cbModalidade.removeAllItems();
            for (Modalidade mo : modDAO.listar()) {
                cbModalidade.addItem(mo);
            }

            InstrutorDAO instDAO = new InstrutorDAO();
            cbInstrutor.removeAllItems();
            // Adiciona um item nulo ou vazio opcional se quiseres, ou lista normal
            for (Instrutor i : instDAO.listar()) {
                cbInstrutor.addItem(i);
            }

            // Status pré-definidos baseados no check do banco
            cbStatus.removeAllItems();
            cbStatus.addItem("Ativa");
            cbStatus.addItem("Trancada");
            cbStatus.addItem("Cancelada");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar listas dos combos: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    public void preencherTabela() {
        List<Matricula> lista = controller.listarMatriculas();
        
        DefaultTableModel modelo = (DefaultTableModel) tabela.getModel();
        modelo.setRowCount(0); // Limpa as linhas antigas da tabela
        
        if (lista != null) {
            for (Matricula m : lista) {
                modelo.addRow(new Object[]{
                    m.getId(),
                    m.getNomeAluno(),
                    m.getNomePlano(),
                    m.getNomeModalidade(),
                    m.getNomeInstrutor() != null ? m.getNomeInstrutor() : "Nenhum",
                    m.getDataMatricula(),
                    m.getStatusMat()
                });
            }
        }
    }
