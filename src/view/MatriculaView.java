    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        try {
            Aluno alunoSel = (Aluno) cbAluno.getSelectedItem();
            Plano planoSel = (Plano) cbPlano.getSelectedItem();
            Modalidade modSel = (Modalidade) cbModalidade.getSelectedItem();
            Instrutor instSel = (Instrutor) cbInstrutor.getSelectedItem();

            if (alunoSel == null || planoSel == null || modSel == null) {
                JOptionPane.showMessageDialog(this, "Certifique-se de que Aluno, Plano e Modalidade estão selecionados.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int idAluno = alunoSel.getId();
            int idPlano = planoSel.getId();
            int idMod = modSel.getIdMod();
            Integer idTutor = (instSel != null) ? instSel.getId() : null;

            String dataStr = txtDataInicio.getText();
            String status = (String) cbStatus.getSelectedItem();

            controller.salvar(idAluno, idPlano, idMod, idTutor, dataStr, status);

            JOptionPane.showMessageDialog(this, "Matrícula realizada com sucesso!");
            txtDataInicio.setText("");
            preencherTabela();

       } catch (SQLException | IllegalArgumentException e) {
    JOptionPane.showMessageDialog(this, "Erro ao salvar matrícula: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
}
    
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        int linhaSelecionada = tabela.getSelectedRow();
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma matrícula na tabela para excluir.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // Converte com segurança para int (evita ClassCastException se vier como Integer)
            Object valorId = tabela.getValueAt(linhaSelecionada, 0);
            int idMat = (valorId instanceof Integer) ? (Integer) valorId : Integer.parseInt(valorId.toString());
            
            controller.excluir(idMat);

            JOptionPane.showMessageDialog(this, "Matrícula excluída com sucesso!");
            preencherTabela();
      } catch (SQLException e) {
    JOptionPane.showMessageDialog(this, "Erro ao excluir matrícula: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnExcluirActionPerformed

