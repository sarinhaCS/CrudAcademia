    private DefaultTableModel modelo;
    private Integer idSelecionado = null;
 
    public PlanoView() {
        initComponents();            // codigo gerado pelo designer
        setLocationRelativeTo(null); // centraliza a janela
 
        // modelo da tabela com as colunas do CRUD (nao editavel)
        modelo = new DefaultTableModel(
                new String[]{"ID", "Plano", "Valor (R$)", "Duração (meses)"}, 0) {
            @Override public boolean isCellEditable(int r, int c) { return false; }
        };
        tabela.setModel(modelo);
        tabela.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tabela.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) preencherCamposComLinhaSelecionada();
        });
 
        atualizarBotoes();
    }
 
    private void preencherCamposComLinhaSelecionada() {
        int linha = tabela.getSelectedRow();
        if (linha < 0) return;
        idSelecionado = (Integer) modelo.getValueAt(linha, 0);
        txtNome.setText((String) modelo.getValueAt(linha, 1));
        txtValor.setText((String) modelo.getValueAt(linha, 2));
        txtDuracao.setText(modelo.getValueAt(linha, 3).toString());
        atualizarBotoes();
    }
 
    private void atualizarBotoes() {
        boolean editando = idSelecionado != null;
        btnSalvar.setEnabled(!editando);
        btnAlterar.setEnabled(editando);
        btnExcluir.setEnabled(editando);
    }
 
    // ----- metodos usados pelo Controller (nao mudam) -----
    public String getNome() { return txtNome.getText().trim(); }
    public String getValor() { return txtValor.getText().trim(); }
    public String getDuracao() { return txtDuracao.getText().trim(); }
    public String getBusca() { return txtBusca.getText().trim(); }
    public Integer getIdSelecionado() { return idSelecionado; }
 
    public void exibirPlanos(List<Plano> planos) {
        idSelecionado = null;
        modelo.setRowCount(0);
        for (Plano p : planos) {
            modelo.addRow(new Object[]{
                p.getId(), p.getNomePlano(),
                String.format(PT_BR, "%.2f", p.getValor()),   // 119,90 (sem separador de milhar)
                p.getDuracaoMeses()});
        }
        atualizarBotoes();
    }
 
    public void limparCampos() {
        txtNome.setText("");
        txtValor.setText("");
        txtDuracao.setText("");
        tabela.clearSelection();
        idSelecionado = null;
        atualizarBotoes();
        txtNome.requestFocus();
    }
 
    public void mostrarMensagem(String msg) {
        JOptionPane.showMessageDialog(this, msg);
    }
 
    public void mostrarErro(String msg) {
        JOptionPane.showMessageDialog(this, msg, "Erro", JOptionPane.ERROR_MESSAGE);
    }
 
    public boolean confirmar(String msg) {
        return JOptionPane.showConfirmDialog(this, msg, "Confirmacao",
                JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION;
    }
 
